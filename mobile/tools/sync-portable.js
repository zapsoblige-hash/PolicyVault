"use strict";

/*
 * PolicyVault mobile — PORTABLE-ARTIFACT SYNC + HASH PIN.
 *
 * The mobile client's entire security-relevant layer is the SAME BYTES the
 * reviewed web client runs. This tool is the only sanctioned way those
 * bytes enter `mobile/www/vendor/`, and its `--check` mode is a HARD BUILD
 * GATE: if what is committed under `mobile/www/vendor/` is not what this
 * tool would produce from the current repository sources, the build FAILS.
 * A mobile release whose verifier bytes are not the reviewed verifier bytes
 * must be structurally impossible, not merely unlikely
 * (docs/postlaunch/mobile-architecture-decision.md §6.2(a), §7.1).
 *
 *   node mobile/tools/sync-portable.js            # regenerate vendor/ + pins
 *   node mobile/tools/sync-portable.js --check    # verify, exit 1 on drift
 *
 * WHY A COPY AT ALL, RATHER THAN A BUILD-TIME REFERENCE: a Capacitor
 * payload is a self-contained directory that `npx cap sync` copies into
 * the native projects. The app must therefore physically carry the files.
 * Copying is the risk; the pin file + `--check` is the control. There is
 * no transformation, no minifier, no bundler, and no re-translation step
 * anywhere in this path — see EMISSION MODES below.
 *
 * ---------------------------------------------------------------------
 * EMISSION MODES (exactly two, both deterministic)
 * ---------------------------------------------------------------------
 *
 *  "verbatim"  The destination file's bytes are IDENTICAL to the source
 *              file's bytes. Used for web/core-bundle.js and
 *              web/verify-intent.js, which are already browser-loadable
 *              (each is an IIFE that installs itself on `window` when one
 *              exists). sha256(dest) === sha256(src), and the test suite
 *              asserts that equality directly.
 *
 *  "cjs-host"  The source is a Node CommonJS module that CANNOT be loaded
 *              by a plain <script> tag (top-level `require(...)` /
 *              `module.exports`). Its bytes are embedded VERBATIM inside a
 *              fixed, deterministic wrapper that supplies `module`,
 *              `exports`, and a CLOSED `require` which resolves ONLY
 *              "crypto"/"node:crypto" — and resolves it to the crypto shim
 *              that is ALREADY INSIDE the reviewed core bundle
 *              (`window.PolicyVaultCore.require("crypto")`), so no second
 *              crypto implementation is introduced anywhere. Anything else
 *              throws (fail closed). This is the same technique
 *              web/tools/build-core-bundle.js uses to embed core sources;
 *              the wrapper adds no logic to the embedded module and the
 *              embedded bytes are recoverable exactly.
 *
 * The pin file (mobile/www/vendor-pins.json) records, for every artifact, the
 * sha256 of the REPOSITORY SOURCE and the sha256 of the EMITTED FILE. The
 * source digest is what proves "the mobile app runs the reviewed bytes";
 * the emitted digest is what the app displays on its Build-integrity
 * screen and what `--check` compares against on disk.
 */

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const REPO_ROOT = path.join(__dirname, "..", "..");
const MOBILE_ROOT = path.join(REPO_ROOT, "mobile");
const VENDOR_DIR = path.join(MOBILE_ROOT, "www", "vendor");
/* The pin document ships INSIDE the payload (www/vendor-pins.json), not
 * beside it: the Build-integrity screen fetches it from the app's own
 * origin at runtime, so it must be part of what `cap copy` carries into
 * the native projects. The same file is the committed pin record. */
const PINS_PATH = path.join(MOBILE_ROOT, "www", "vendor-pins.json");

/*
 * The CLOSED artifact set. Adding a row here is a security-relevant change:
 * it widens what the mobile app executes. Nothing is copied that is not
 * listed, and the list is ordered (pin-file output is order-stable).
 */
const ARTIFACTS = [
  {
    source: "web/core-bundle.js",
    dest: "core-bundle.js",
    mode: "verbatim",
    global: "PolicyVaultCore",
    why: "The sha256-pinned deterministic shared core. Generated by web/tools/build-core-bundle.js; its own header pins every embedded core/ source. Installs window.PolicyVaultCore."
  },
  {
    source: "web/verify-intent.js",
    dest: "verify-intent.js",
    mode: "verbatim",
    global: "PolicyVaultVerifyIntent",
    why: "The pure createVerifyIntent(core) pre-sign verifier — the DO-NOT-SIGN decision itself. DOM-free by construction; installs window.PolicyVaultVerifyIntent when a core bundle is present, and a permanently-refusing instance when it is not."
  },
  {
    source: "sdk/src/http-client.js",
    dest: "http-client.js",
    mode: "cjs-host",
    global: "PolicyVaultHttpClient",
    why: "The zero-runtime-dependency PolicyVault API client (transport only: no financial authority, no policy semantics, no verification). Node CommonJS, so it is host-wrapped rather than copied raw."
  }
];

/* Fixed wrapper text. Deterministic: no timestamps, no environment data,
 * no randomness, and no dependence on anything but the embedded bytes and
 * the artifact's declared global name. */
function cjsHostWrapper(embedded, globalName, sourceRel, sourceSha) {
  const header = [
    "/*",
    " * PolicyVault mobile vendored artifact — GENERATED FILE, do not edit by hand.",
    " * Generator: mobile/tools/sync-portable.js (deterministic; verify with",
    " * `node mobile/tools/sync-portable.js --check`).",
    " *",
    ` * Embedded VERBATIM: ${sourceRel}  sha256:${sourceSha}`,
    " *",
    " * The wrapper below supplies module/exports and a CLOSED require that",
    ' * resolves only "crypto"/"node:crypto", to the crypto shim already inside',
    " * the reviewed core bundle. It adds no logic to the embedded module.",
    " */"
  ].join("\n");

  return [
    header,
    "(function (globalScope) {",
    '  "use strict";',
    "  var module = { exports: {} };",
    "  var exports = module.exports;",
    "  function require(request) {",
    '    if (request === "crypto" || request === "node:crypto") {',
    "      var core = globalScope.PolicyVaultCore;",
    '      if (!core || typeof core.require !== "function") {',
    '        throw new Error("policyvault-mobile: the core bundle is not loaded, so no crypto is available — failing closed");',
    "      }",
    '      return core.require("crypto");',
    "    }",
    '    throw new Error("policyvault-mobile: module " + JSON.stringify(request) + " is outside the vendored module set — failing closed");',
    "  }",
    "  /* ---- BEGIN VERBATIM " + sourceRel + " ---- */",
    embedded.replace(/\n$/, ""),
    "  /* ---- END VERBATIM " + sourceRel + " ---- */",
    `  globalScope.${globalName} = module.exports;`,
    '})(typeof globalThis !== "undefined" ? globalThis : this);',
    ""
  ].join("\n");
}

function sha256Hex(text) {
  return crypto.createHash("sha256").update(text, "utf8").digest("hex");
}

/*
 * Produce the full emission plan in memory. Pure: reads repository
 * sources, writes nothing. Both `sync` and `--check` run this exact
 * function, so the two modes can never disagree about what "correct"
 * means.
 */
function plan(options) {
  const vendorDir = (options && options.vendorDir) || VENDOR_DIR;
  const files = ARTIFACTS.map((a) => {
    const abs = path.join(REPO_ROOT, a.source);
    const sourceText = fs.readFileSync(abs, "utf8");
    const sourceSha = sha256Hex(sourceText);
    const emitted = a.mode === "verbatim"
      ? sourceText
      : cjsHostWrapper(sourceText, a.global, a.source, sourceSha);
    return {
      source: a.source,
      dest: `www/vendor/${a.dest}`,
      destAbs: path.join(vendorDir, a.dest),
      mode: a.mode,
      global: a.global,
      why: a.why,
      sourceSha256: sourceSha,
      emittedSha256: sha256Hex(emitted),
      emitted
    };
  });

  /* The pin document. `pinsVersion` is a schema version: an older reader
   * meeting a newer document must fail closed rather than reinterpret it
   * (CLAUDE.md versioning rule). */
  const pins = {
    pinsVersion: "policyvault-mobile-vendor-pins/1",
    generator: "mobile/tools/sync-portable.js",
    note: "Every file under mobile/www/vendor/ is produced from a repository source by this generator. sourceSha256 proves the mobile app runs the reviewed bytes; emittedSha256 is what the app's Build-integrity screen displays and what --check compares on disk.",
    artifacts: files.map((f) => ({
      source: f.source,
      dest: f.dest,
      mode: f.mode,
      global: f.global,
      sourceSha256: f.sourceSha256,
      emittedSha256: f.emittedSha256,
      why: f.why
    }))
  };

  return { files, pins, pinsText: JSON.stringify(pins, null, 2) + "\n" };
}

function writeAll(options) {
  const vendorDir = (options && options.vendorDir) || VENDOR_DIR;
  const pinsPath = (options && options.pinsPath) || PINS_PATH;
  const { files, pinsText } = plan({ vendorDir });
  fs.mkdirSync(vendorDir, { recursive: true });
  for (const f of files) fs.writeFileSync(f.destAbs, f.emitted);
  fs.writeFileSync(pinsPath, pinsText);
  return files;
}

/*
 * Verify the committed tree. Returns an array of human-readable drift
 * descriptions; empty means clean. Checks BOTH directions that matter:
 * every expected file exists with exactly the expected bytes, AND the
 * vendor directory contains nothing else (an unlisted file in the payload
 * would be code the review never covered).
 */
function checkAll(options) {
  /* `vendorDir`/`pinsPath` are overridable so a test can verify the gate's
   * DRIFT and UNLISTED behaviour against a scratch copy instead of
   * mutating the committed payload. Mutating shared state to test a check
   * would race every other suite that reads the payload — the project's
   * standing rule that shared mutable state stays strictly serial applies
   * to test fixtures too. */
  const vendorDir = (options && options.vendorDir) || VENDOR_DIR;
  const pinsPath = (options && options.pinsPath) || PINS_PATH;
  const { files, pinsText } = plan({ vendorDir });
  const problems = [];

  for (const f of files) {
    if (!fs.existsSync(f.destAbs)) {
      problems.push(`MISSING: ${f.dest} (expected from ${f.source})`);
      continue;
    }
    const onDisk = fs.readFileSync(f.destAbs, "utf8");
    if (onDisk !== f.emitted) {
      problems.push(
        `DRIFT: ${f.dest} is sha256:${sha256Hex(onDisk)} but ${f.source} (sha256:${f.sourceSha256}) currently emits sha256:${f.emittedSha256}`
      );
    }
  }

  if (fs.existsSync(vendorDir)) {
    const expected = new Set(files.map((f) => path.basename(f.destAbs)));
    for (const name of fs.readdirSync(vendorDir)) {
      if (name === ".gitkeep") continue;
      if (!expected.has(name)) problems.push(`UNLISTED: mobile/www/vendor/${name} is not produced by this generator — the payload must contain no unreviewed code`);
    }
  }

  if (!fs.existsSync(pinsPath)) {
    problems.push("MISSING: mobile/www/vendor-pins.json");
  } else if (fs.readFileSync(pinsPath, "utf8") !== pinsText) {
    problems.push("DRIFT: mobile/www/vendor-pins.json does not match the current sources — run node mobile/tools/sync-portable.js");
  }

  return problems;
}

/*
 * Where `npx cap copy` deposits the payload inside each native project.
 * Checking THESE is the §7.1 hard gate "assert sha256(packaged
 * core-bundle.js) == repo artifact": `cap copy` is the last step that
 * could substitute the verifier, and it runs after every source check.
 * A platform directory that does not exist is skipped, not failed —
 * platforms are added on demand.
 */
const PACKAGED_PAYLOADS = [
  { label: "android", dir: path.join(MOBILE_ROOT, "android", "app", "src", "main", "assets", "public") },
  { label: "ios", dir: path.join(MOBILE_ROOT, "ios", "App", "App", "public") }
];

function checkPackaged() {
  const results = [];
  for (const target of PACKAGED_PAYLOADS) {
    if (!fs.existsSync(target.dir)) {
      results.push({ label: target.label, present: false, problems: [] });
      continue;
    }
    results.push({
      label: target.label,
      present: true,
      problems: checkAll({
        vendorDir: path.join(target.dir, "vendor"),
        pinsPath: path.join(target.dir, "vendor-pins.json")
      })
    });
  }
  return results;
}

if (require.main === module) {
  const check = process.argv.includes("--check");
  const checkPackagedFlag = process.argv.includes("--check-packaged");

  if (checkPackagedFlag) {
    const results = checkPackaged();
    let failed = false;
    for (const r of results) {
      if (!r.present) {
        console.log(`mobile/tools/sync-portable.js --check-packaged: ${r.label} platform not added — skipped.`);
        continue;
      }
      if (r.problems.length) {
        failed = true;
        console.error(`--check-packaged FAILED for ${r.label}: the copied payload is not the reviewed payload:`);
        for (const p of r.problems) console.error("  " + p);
      } else {
        console.log(`--check-packaged OK for ${r.label} — the copied payload matches the repository sources.`);
      }
    }
    if (failed) {
      console.error("\nRe-run `npx cap sync` and investigate before shipping. A release whose verifier bytes are not the reviewed bytes must never be built.");
      process.exit(1);
    }
    process.exit(0);
  }

  if (check) {
    const problems = checkAll();
    if (problems.length) {
      console.error("mobile/tools/sync-portable.js --check FAILED — the packaged portable layer is not the reviewed portable layer:");
      for (const p of problems) console.error("  " + p);
      console.error("\nRun `node mobile/tools/sync-portable.js` and re-review the diff. Never hand-edit mobile/www/vendor/.");
      process.exit(1);
    }
    console.log(`mobile/tools/sync-portable.js --check OK — ${ARTIFACTS.length} vendored artifacts match their repository sources.`);
  } else {
    const files = writeAll();
    for (const f of files) {
      console.log(`${f.dest}  <=  ${f.source}  [${f.mode}]  source sha256:${f.sourceSha256}`);
    }
    console.log(`mobile/www/vendor-pins.json updated (${files.length} artifacts).`);
  }
}

module.exports = { ARTIFACTS, REPO_ROOT, MOBILE_ROOT, VENDOR_DIR, PINS_PATH, PACKAGED_PAYLOADS, plan, writeAll, checkAll, checkPackaged, sha256Hex };
