P("        require(poolNoteNew.identifierType == IDENTIFIER_COVENANT_ID);");
P("        require(!poolNoteNew.isMinter);");
P("        require(poolNoteNew.amount >= 0);");
P("        require(poolNoteNew.amount == poolAmount + delta);");
P("        int selfOut = OpCovOutputIdx(tokenCovenantId, 0);");
P("        int poolNoteOut = OpCovOutputIdx(tokenCovenantId, 1);");
P("        validateOutputStateWithTemplate(selfOut, selfNew, templatePrefix, templateSuffix, templateVmHash);");
P("        validateOutputStateWithTemplate(poolNoteOut, poolNoteNew, templatePrefix, templateSuffix, templateVmHash);");
P("        require(tx.outputs[selfOut].value >= tx.inputs[ourIn].value);");
P("    }");
P("");
P("    /* PROTOCOL FEE output: plain P2PK to the profile's pinned fee key, bounded");
P("     * by the owner's maxProtocolFeeKas; returns its value. */");
P("    function protocolFeeValue(int feeOutIdx, pubkey poolFeePk, int maxProtocolFeeKas) : (int) {");
P(`        require(bytes(OpOutputCovenantId(feeOutIdx)) == bytes(${ZERO}));`);
P("        require(tx.outputs[feeOutIdx].scriptPubKey == new ScriptPubKeyP2PK(poolFeePk));");
