P("        require(protoFee >= 0);");
P("        require(protoFee <= maxProtocolFeeKas);");
P("        return protoFee;");
P("    }");
P("");
P("    /* SIGHASH gate + the leaf's key is the sole authority. */");
P("    function requireAgentAuthorization(byte[] agentSig, pubkey agentPk) {");
P("        require(agentSig.length == 65);");
P("        (byte[] sigBody, byte[] hashByte) = agentSig.split(64);");
P("        require(hashByte == bytes(0x01));");
P("        require(checkSig(sig(agentSig), agentPk));");
