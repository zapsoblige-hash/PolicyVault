// ---- tokenAgentSpend (v0.5 semantics + SIGHASH gate + v0.6 leaf) ----------
P("    #[covenant.singleton]");
P("    function tokenAgentSpend(");
P("        State prevState,");
P("        State newState,");
P("        KCC20State selfNew,");
P("        KCC20State recipientNew,");
P(params(AGENT_PARAMS));
P("        byte[] policySiblings,");
P("        int policyPathBits,");
P("        int periodsElapsed,");
P("        pubkey recipientPk,");
P("        byte[] recipientSiblings,");
P("        int recipientPathBits,");
P("        byte[] agentSig");
P("    ) {");
P("        require(prevState.paused == 0);");
P("        requireAgentAuthorization(agentSig, agentPk);");
P("");
P("        /* BINDING A — exact pinned token family, exact shape (1 in, 2 out:");
P("         * self continuation + single recipient), no foreign covenants. */");
P("        require(OpCovInputCount(tokenCovenantId) == 1);");
P("        require(OpCovOutputCount(tokenCovenantId) == 2);");
P("        int tokIn = OpCovInputIdx(tokenCovenantId, 0);");
P("        requireNoForeignCovenantInputs(tokIn);");
P("");
P("        /* BINDING B — the token input's revealed redeem is proven BEFORE its");
P("         * state is trusted; template carriage from that proven input. */");
P("        KCC20State prevTok = readInputStateWithTemplate(");
P("            tokIn,");
P("            templatePrefixLen,");
P("            templateSuffixLen,");
P("            templateVmHash");
P("        );");
P("        int sigLen = OpTxInputScriptSigLen(tokIn);");
P("        int redeemStart = sigLen - (templatePrefixLen + templateStateLen + templateSuffixLen);");
P("        byte[] templatePrefix = OpTxInputScriptSigSubstr(tokIn, redeemStart, redeemStart + templatePrefixLen);");
P("        byte[] templateSuffix = OpTxInputScriptSigSubstr(tokIn, sigLen - templateSuffixLen, sigLen);");
P("");
P("        byte[32] selfId = OpInputCovenantId(this.activeInputIndex);");
P("        require(prevTok.ownerIdentifier == selfId);");
P("        require(prevTok.identifierType == IDENTIFIER_COVENANT_ID);");
P("        require(!prevTok.isMinter);");
P("        require(selfNew.ownerIdentifier == selfId);");
P("        require(selfNew.identifierType == IDENTIFIER_COVENANT_ID);");
P("        require(!selfNew.isMinter);");
P("        require(bytes(selfNew.ownerIdentifier) != bytes(recipientPk));");
P("        require(bytes(recipientNew.ownerIdentifier) == bytes(recipientPk));");
P("        require(recipientNew.identifierType == IDENTIFIER_PUBKEY);");
P("        require(!recipientNew.isMinter);");
P("");
P("        /* TOKEN DOMAIN — exact conservation + token-denominated policy. */");
P("        int spendAmount = recipientNew.amount;");
P("        require(spendAmount > 0);");
P("        require(selfNew.amount >= 0);");
P("        require(selfNew.amount == prevTok.amount - spendAmount);");
P(`        requireAgentTransition(prevState, newState, spendAmount, 0, ${AGENT_ARGS}, policySiblings, policyPathBits, periodsElapsed);`);
P("        requireAgentRecipient(agentRecipientRoot, recipientPk, recipientSiblings, recipientPathBits);");
P("");
P("        validateOutputStateWithTemplate(");
P("            OpCovOutputIdx(tokenCovenantId, 0),");
P("            selfNew,");
P("            templatePrefix,");
P("            templateSuffix,");
P("            templateVmHash");
P("        );");
P("        validateOutputStateWithTemplate(");
P("            OpCovOutputIdx(tokenCovenantId, 1),");
P("            recipientNew,");
P("            templatePrefix,");
P("            templateSuffix,");
P("            templateVmHash");
P("        );");
P("");
P("        requireKasDomainsSpend(prevState, newState, tokIn, agentMaxFeePerTx, agentMaxCarryKas);");
P("        requireVaultGlobalPreserved(prevState, newState);");
P("    }");
P("");

// ---- tokenAtomicSell --------------------------------------------------------
P("    /* ATOMIC SELL: give up EXACTLY amountIn tokens to the approved pool's");
P("     * reserve note; receive net KAS proceeds (pool KAS decrease minus the");
P("     * bounded protocol fee) >= minKasOut and >= the owner's floor price, at");
P("     * the owner-approved destination (type A: accrue to swapPrincipal; type B:");
P("     * exact plain P2PK output). Outputs: successor, our note, pool note, pool");
P("     * successor, protocol fee (+ proceeds for type B) — nothing else. */");
P("    #[covenant.singleton]");
P("    function tokenAtomicSell(");
P("        State prevState,");
P("        State newState,");
P("        KCC20State selfNew,");
P("        KCC20State poolNoteNew,");
P(params(AGENT_PARAMS));
P("        byte[] policySiblings,");
P("        int policyPathBits,");
P("        int periodsElapsed,");
P(params(SWAP_PARAMS));
P("        byte[] swapSiblings,");
P("        int swapPathBits,");
P("        int amountIn,");
P("        int minKasOut,");
P("        int proceedsOutIdx,");
P("        int feeOutIdx,");
P("        byte[] agentSig");
P("    ) {");
P("        require(prevState.paused == 0);");
P("        requireAgentAuthorization(agentSig, agentPk);");
P(`        requireSwapPolicy(prevState.swapRoot, ${SWAP_ARGS}, swapSiblings, swapPathBits);`);
P("        require(directionMask >= 1);");
P("        require(directionMask <= 3);");
P("        require(directionMask % 2 == 1);");
P("        requireSwapShape(poolCovenantId, poolTemplateVmHash, poolPrefixLen, poolSuffixLen);");
P("        require(amountIn > 0);");
P("        requireTokenNotes(selfNew, poolNoteNew, poolCovenantId, amountIn);");
P("");
P("        /* KAS proceeds = the pool's exact KAS decrease minus the protocol fee */");
P("        int poolIn = OpCovInputIdx(poolCovenantId, 0);");
P("        int poolOut = OpCovOutputIdx(poolCovenantId, 0);");
P("        int kasOut = tx.inputs[poolIn].value - tx.outputs[poolOut].value;");
P("        require(kasOut > 0);");
P("        (int protoFee) = protocolFeeValue(feeOutIdx, poolFeePk, maxProtocolFeeKas);");
P("        require(protoFee < kasOut);");
P("        int netProceeds = kasOut - protoFee;");
P("        require(minKasOut > 0);");
P("        require(netProceeds >= minKasOut);");
P("        require(sellFloorDen > 0);");
P("        require(netProceeds * sellFloorDen >= amountIn * sellFloorNum);");
P("");
P("        if (destScheme == IDENTIFIER_COVENANT_ID) {");
P("            /* type A: proceeds accrue to the protected principal; the proceeds");
P("             * index MUST name our own successor; no proceeds output exists */");
P(`            require(bytes(destIdentity) == bytes(${ZERO}));`);
P("            require(proceedsOutIdx == OpAuthOutputIdx(this.activeInputIndex, 0));");
P("            require(newState.swapPrincipal == prevState.swapPrincipal + netProceeds);");
P("            require(tx.outputs.length == 5);");
P("        } else {");
P("            /* type B: exact plain P2PK proceeds output to the allowlisted key */");
P("            require(destScheme == IDENTIFIER_PUBKEY);");
P("            require(feeOutIdx != proceedsOutIdx);");
P(`            require(bytes(OpOutputCovenantId(proceedsOutIdx)) == bytes(${ZERO}));`);
P("            require(tx.outputs[proceedsOutIdx].scriptPubKey == new ScriptPubKeyP2PK(destIdentity));");
P("            require(tx.outputs[proceedsOutIdx].value == netProceeds);");
P("            require(newState.swapPrincipal == prevState.swapPrincipal);");
P("            require(tx.outputs.length == 6);");
P("        }");
P("");
P(`        requireAgentTransition(prevState, newState, amountIn, 0, ${AGENT_ARGS}, policySiblings, policyPathBits, periodsElapsed);`);
P("        requireFeeReserveDomain(prevState, newState, agentMaxFeePerTx);");
P("        requireVaultGlobalPreserved(prevState, newState);");
P("    }");
P("");

// ---- tokenAtomicBuy ---------------------------------------------------------
P("    /* ATOMIC BUY: pay KAS consideration (the pool's exact KAS increase + the");
P("     * bounded protocol fee) from the protected swapPrincipal ONLY, bounded by");
P("     * maxKasIn, the agent's kasMaxPerSwap / kasPeriodBudget and the owner's");
P("     * ceiling price; receive EXACTLY tokensOut into OUR position (type A only:");
P("     * tokens never leave to a third party on a buy). Outputs: successor, our");
P("     * note, pool note, pool successor, protocol fee — nothing else. */");
P("    #[covenant.singleton]");
P("    function tokenAtomicBuy(");
P("        State prevState,");
P("        State newState,");
P("        KCC20State selfNew,");
P("        KCC20State poolNoteNew,");
P(params(AGENT_PARAMS));
P("        byte[] policySiblings,");
P("        int policyPathBits,");
P("        int periodsElapsed,");
P(params(SWAP_PARAMS));
P("        byte[] swapSiblings,");
P("        int swapPathBits,");
