P(`        requireAgentTransition(prevState, newState, 0, kasSpend, ${AGENT_ARGS}, policySiblings, policyPathBits, periodsElapsed);`);
P("        requireFeeReserveDomain(prevState, newState, agentMaxFeePerTx);");
P("        requireVaultGlobalPreserved(prevState, newState);");
P("    }");
P("");

// ---- ownerControl (6 selectors, one checkSig) -----------------------------
P("    /* Owner operations behind ONE entrypoint + bounded opSelector (static");
P("     * sig-ops: spend + sell + buy + ownerControl + ownerRecover = 5 <= 15).");
P("     * Owner operations NEVER move tokens and NEVER admit a foreign covenant. */");
P("    #[covenant.singleton]");
P("    function ownerControl(State prevState, State newState, int opSelector, sig ownerSig) {");
P("        require(checkSig(ownerSig, owner));");
P("        require(opSelector >= 0);");
P("        require(opSelector <= 5);");
