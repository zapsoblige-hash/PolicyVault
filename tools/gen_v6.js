P("            require(newState.paused == prevState.paused);");
P("            require(newState.agentRoot == prevState.agentRoot);");
P("            require(newState.policyNonce == prevState.policyNonce + 1);");
P("        } else {");
P("            /* opSelector == 5 (bounded to [0,5]): fundSwapPrincipal — increase the");
P("             * protected principal only */");
P("            require(newState.swapPrincipal > prevState.swapPrincipal);");
P("            require(newState.feeReserve == prevState.feeReserve);");
P("            require(newState.paused == prevState.paused);");
P("            require(newState.agentRoot == prevState.agentRoot);");
P("            require(newState.swapRoot == prevState.swapRoot);");
P("            require(newState.policyNonce == prevState.policyNonce);");
P("        }");
P("        }");
P("        }");
P("        }");
P("        }");
P("        requireExactSuccessorValue(newState.feeReserve + newState.swapPrincipal);");
P("    }");
P("");

// ---- ownerRecover (terminal; everything returns to the owner key) ----------
P("    /* Break-glass recovery: the controller terminates, its fee reserve AND");
P("     * swap principal pay out to the owner (output 0), and — if the position");
