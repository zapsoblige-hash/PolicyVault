P("            byte[] templateSuffix = OpTxInputScriptSigSubstr(tokIn, sigLen - templateSuffixLen, sigLen);");
P("            byte[32] selfId = OpInputCovenantId(this.activeInputIndex);");
P("            require(prevTok.ownerIdentifier == selfId);");
P("            require(prevTok.identifierType == IDENTIFIER_COVENANT_ID);");
P("            require(bytes(recipientNew.ownerIdentifier) == bytes(owner));");
P("            require(recipientNew.identifierType == IDENTIFIER_PUBKEY);");
P("            require(!recipientNew.isMinter);");
P("            require(recipientNew.amount == prevTok.amount);");
P("            validateOutputStateWithTemplate(");
P("                OpCovOutputIdx(tokenCovenantId, 0),");
P("                recipientNew,");
P("                templatePrefix,");
P("                templateSuffix,");
P("                templateVmHash");
P("            );");
