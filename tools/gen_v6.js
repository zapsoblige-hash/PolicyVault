P("        require(nextStates.length == 0);");
P("        require(tx.outputs[0].scriptPubKey == new ScriptPubKeyP2PK(owner));");
P("        require(tx.outputs[0].value == prevState.feeReserve + prevState.swapPrincipal);");
P(`        require(bytes(descriptorHash) != bytes(${ZERO}));`);
P("        int familyInputs = OpCovInputCount(tokenCovenantId);");
P("        require(familyInputs <= 1);");
P("        if (familyInputs == 1) {");
P("            require(OpCovOutputCount(tokenCovenantId) == 1);");
P("            int tokIn = OpCovInputIdx(tokenCovenantId, 0);");
P("            requireNoForeignCovenantInputs(tokIn);");
P("            KCC20State prevTok = readInputStateWithTemplate(");
P("                tokIn,");
P("                templatePrefixLen,");
P("                templateSuffixLen,");
